/* Crie uma função que receba um nome e retorne uma mensagem de boas-vindas. */

function saudacaoUsandoTipoString(nome: string): string {
    return `Bem vindo(a) ao nosso hotel, ${nome}!`
}

console.log(saudacaoUsandoTipoString('Chapolin Colorado')); // Bem vindo(a) ao nosso hotel, Chapolin Colorado!
